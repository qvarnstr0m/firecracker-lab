#!/usr/bin/env bash
# Turn a container image into an ext4 root filesystem for a microVM.
#
#   rootfs/from-oci.sh <image> [name]
#
# Steps, all visible below:
#   1. docker create + docker export  -> the image's flattened filesystem
#   2. docker image inspect           -> Entrypoint, Cmd, Env, WorkingDir
#   3. add /sbin/fc-init and /etc/fc-entrypoint.sh
#   4. mkfs.ext4 -d                   -> build/rootfs/<name>.ext4
#
# The image needs /bin/sh (fc-init is a shell script). Alpine- and Debian-based
# images work; distroless and scratch images don't.
source "$(dirname "$0")/../lib/common.sh"

image="${1:?usage: $0 <image> [name]}"
# Default name: repository basename without tag, e.g. nginx:alpine -> nginx
default_name="${image##*/}"; default_name="${default_name%%[:@]*}"
name="${2:-$default_name}"
valid_name "$name"

need docker jq mkfs.ext4 tar
out="$ROOTFS_DIR/$name.ext4"
mkdir -p "$ROOTFS_DIR"

case "$ARCH" in
  x86_64)  platform=linux/amd64 ;;
  aarch64) platform=linux/arm64 ;;
  *) die "unsupported arch $ARCH" ;;
esac

if ! docker image inspect "$image" >/dev/null 2>&1; then
  show docker pull --platform "$platform" "$image"
fi

work="$(mktemp -d)"
cid=""
cleanup() {
  [[ -n "$cid" ]] && docker rm -f "$cid" >/dev/null 2>&1
  as_root rm -rf "$work"
}
trap cleanup EXIT

log "exporting $image filesystem"
cid="$(docker create --platform "$platform" "$image")"
mkdir -p "$work/root"
# Extract as root so file ownership (e.g. nginx:nginx) survives into the ext4 image.
docker export "$cid" | as_root tar -C "$work/root" --numeric-owner -xf -

log "writing init and entrypoint"
config="$(docker image inspect "$image" | jq '.[0].Config')"
{
  echo "# generated by rootfs/from-oci.sh from $image"
  jq -r '(.Env // [])[] | "export " + (. | @sh)' <<<"$config"
  jq -r 'if (.WorkingDir // "") != "" then "cd " + (.WorkingDir | @sh) else empty end' <<<"$config"
  jq -r '((.Entrypoint // []) + (.Cmd // [])) as $argv
         | if ($argv | length) == 0 then "exec /bin/sh"
           else "exec " + ($argv | map(@sh) | join(" ")) end' <<<"$config"
} > "$work/fc-entrypoint.sh"
jq -r '((.Entrypoint // []) + (.Cmd // [])) | join(" ")' <<<"$config" > "$work/fc-entrypoint.cmd"
sed 's/^/    /' "$work/fc-entrypoint.sh" >&2

[[ -x "$work/root/bin/sh" || -L "$work/root/bin/sh" ]] || die "$image has no /bin/sh; fc-init can't run"

as_root install -m 0755 "$REPO_ROOT/rootfs/init/fc-init" "$work/root/sbin/fc-init"
as_root install -m 0644 "$work/fc-entrypoint.sh" "$work/root/etc/fc-entrypoint.sh"
as_root install -m 0644 "$work/fc-entrypoint.cmd" "$work/root/etc/fc-entrypoint.cmd"
# docker export leaves these as empty placeholders.
as_root rm -f "$work/root/etc/resolv.conf" "$work/root/etc/hostname"
echo "nameserver $FC_GUEST_DNS" | as_root tee "$work/root/etc/resolv.conf" >/dev/null
as_root touch "$work/root/etc/hostname"

# Size: content + 50% + 64 MiB headroom.
used_mib="$(as_root du -sm "$work/root" | cut -f1)"
size_mib=$(( used_mib * 3 / 2 + 64 ))
log "creating ${size_mib} MiB ext4 image"
rm -f "$out"
truncate -s "${size_mib}M" "$out"
show as_root mkfs.ext4 -q -F -L rootfs -d "$work/root" "$out"
as_root chown "$(id -u):$(id -g)" "$out"

log "rootfs: $out"
log "next: make run NAME=<vm> ROOTFS=$name"
